#!/usr/bin/env node
// Static build. The site is plain HTML/CSS/JS, so building is copying the
// deployable files into a directory — plus one optional step: when the
// deployment provides ODOMO_OP_CLIENT_ID, the OpenPanel config in the output is
// written for that environment instead of the committed default.
//
//   node scripts/build.mjs [--out dist]
//
// Env:
//   ODOMO_OP_CLIENT_ID  OpenPanel client id. Unset → the committed
//                       assets/analytics-config.js is copied unchanged.
//   ODOMO_OP_API_URL    API base (the tracker posts to `${apiUrl}/track`).
//                       Defaults to the production ingest.
import { cp, mkdir, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const DEFAULT_API_URL = "https://events.marikita.party/api";

/** Everything a deploy needs; keeps .git, tests and this script out of dist. */
const DEPLOY_ENTRIES = [
  "account-deletion.html",
  "appstore-badge.svg",
  "assets",
  "get.html",
  "googleplay-badge.png",
  "hero-app-screenshot.png",
  "index-website.html",
  "index.html",
  "privacy-policy.html",
  "robots.txt",
  "terms-of-service.html",
];

/** The generated config file. `clientId` empty means tracking is off. */
export function renderConfig({ clientId = "", apiUrl = "" } = {}) {
  const id = clientId.trim();
  const url = (apiUrl.trim() || DEFAULT_API_URL).replace(/\/+$/, "");
  if (url && !/^https?:\/\//.test(url)) {
    throw new Error(`ODOMO_OP_API_URL must be an http(s) URL, got ${url}`);
  }
  return [
    "// Generated by scripts/build.mjs from ODOMO_OP_CLIENT_ID and ODOMO_OP_API_URL.",
    "// The client id is public; never put a client secret here.",
    "window.ODOMO_ANALYTICS = {",
    `  clientId: ${JSON.stringify(id)},`,
    `  apiUrl: ${JSON.stringify(url)},`,
    "};",
    "",
  ].join("\n");
}

function parseOut(argv) {
  const index = argv.indexOf("--out");
  if (index === -1) return path.join(ROOT, "dist");
  const value = argv[index + 1];
  if (!value) throw new Error("--out needs a directory");
  return path.resolve(ROOT, value);
}

export async function build({ out, env = process.env } = {}) {
  const target = out ?? path.join(ROOT, "dist");
  const clientId = (env.ODOMO_OP_CLIENT_ID ?? "").trim();
  const apiUrl = (env.ODOMO_OP_API_URL ?? "").trim();

  await rm(target, { recursive: true, force: true });
  await mkdir(target, { recursive: true });
  for (const entry of DEPLOY_ENTRIES) {
    await cp(path.join(ROOT, entry), path.join(target, entry), {
      recursive: true,
    });
  }

  // Without a client id the committed config is the deployment's config; only
  // an explicit environment overrides it.
  if (clientId) {
    await writeFile(
      path.join(target, "assets", "analytics-config.js"),
      renderConfig({ clientId, apiUrl }),
    );
  }

  return {
    out: target,
    analytics: clientId ? "enabled" : "default (committed config)",
  };
}

const isCli = process.argv[1] === fileURLToPath(import.meta.url);
if (isCli) {
  try {
    const result = await build({ out: parseOut(process.argv) });
    console.log(`built ${path.relative(ROOT, result.out) || "."}`);
    console.log(`analytics: ${result.analytics}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
